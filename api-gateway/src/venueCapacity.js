export function estimateVenueCapacity(venueName, explicitCap) {
  if (explicitCap != null && explicitCap > 0) return explicitCap;
  if (!venueName) return null;
  const lower = venueName.toLowerCase().trim();
  for (const [known, cap] of Object.entries(KNOWN_VENUES)) {
    if (lower === known || lower.includes(known)) return cap;
  }
  if (/\b(stadium|speedway|estadio|stade|coliseum|coliseo|parc des princes)\b/i.test(lower)) return 55000;
  if (/\b(dome|fairgrounds|expo center|sports park|raceway)\b/i.test(lower)) return 25000;
  if (/\b(amphitheater|amphitheatre|pavilion)\b/i.test(lower)) return 18000;
  if (/\b(arena|center|centre|forum|palace|garden|park|field)\b/i.test(lower)) return 15000;
  if (/\b(auditorium|theater|theatre|hall|opera house|ballroom|armory|casino|poppodium|olympia|fillmore)\b/i.test(lower)) return 2500;
  if (/\b(club|bar|lounge|tavern|pub|inn|cafe|café|stage|room|basement|brewery|distillery)\b/i.test(lower)) return 450;
  return 1200;
}
